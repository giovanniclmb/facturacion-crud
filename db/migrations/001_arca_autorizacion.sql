BEGIN;
ALTER TABLE factura_venta
 ADD COLUMN numero_fiscal bigint,
 ADD COLUMN punto_venta_fiscal integer,
 ADD COLUMN tipo_comprobante_fiscal integer,
 ADD COLUMN ambiente_fiscal text,
 ADD COLUMN emisor_fiscal text;
CREATE TABLE arca_serie (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ambiente text NOT NULL, emisor text NOT NULL, punto_venta integer NOT NULL CHECK (punto_venta>0),
 tipo integer NOT NULL CHECK (tipo=11), intento_activo uuid,
 CONSTRAINT uq_arca_serie UNIQUE (ambiente,emisor,punto_venta,tipo)
);
CREATE TABLE arca_intento (
 id uuid PRIMARY KEY,
 factura_id bigint NOT NULL REFERENCES factura_venta(id) ON DELETE RESTRICT,
 serie_id bigint NOT NULL REFERENCES arca_serie(id) ON DELETE RESTRICT,
 usuario_iniciador_id bigint NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
 propietario uuid NOT NULL,
 estado text NOT NULL CHECK (estado IN ('PREPARANDO','ENVIANDO','INCIERTO','AUTORIZADO','RECHAZADO','FALLIDO_ANTES_ENVIO')),
 numero bigint CHECK (numero>0), concepto integer NOT NULL CHECK (concepto=1),
 doc_tipo integer NOT NULL CHECK (doc_tipo=80), doc_numero bigint NOT NULL,
 condicion_iva integer NOT NULL, fecha date NOT NULL, moneda text NOT NULL CHECK (moneda='PES'),
 cotizacion numeric(18,6) NOT NULL CHECK (cotizacion=1), total numeric(18,2) NOT NULL CHECK (total>0),
 hash text NOT NULL, creado timestamptz NOT NULL, actualizado timestamptz NOT NULL,
 cae varchar(255), vencimiento date, errores text NOT NULL, observaciones text NOT NULL,
 version bigint NOT NULL,
 CHECK (estado NOT IN ('ENVIANDO','INCIERTO','AUTORIZADO') OR numero IS NOT NULL),
 CHECK (estado<>'AUTORIZADO' OR (cae IS NOT NULL AND cae ~ '^[0-9]{14}$' AND vencimiento IS NOT NULL))
);
ALTER TABLE arca_serie ADD CONSTRAINT fk_arca_serie_intento FOREIGN KEY(intento_activo) REFERENCES arca_intento(id) ON DELETE RESTRICT;
CREATE INDEX ix_arca_intento_factura_fecha ON arca_intento(factura_id,creado DESC,id DESC);
CREATE INDEX ix_arca_intento_usuario ON arca_intento(usuario_iniciador_id);
CREATE INDEX ix_arca_intento_serie ON arca_intento(serie_id);
CREATE INDEX ix_arca_serie_intento ON arca_serie(intento_activo);
CREATE UNIQUE INDEX uq_arca_factura_activa ON arca_intento(factura_id)
 WHERE estado IN ('PREPARANDO','ENVIANDO','INCIERTO','AUTORIZADO');
CREATE UNIQUE INDEX uq_arca_numero_reservado ON arca_intento(serie_id,numero)
 WHERE numero IS NOT NULL AND estado IN ('PREPARANDO','ENVIANDO','INCIERTO','AUTORIZADO');
COMMIT;
